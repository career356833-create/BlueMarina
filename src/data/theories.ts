export const theories: TheoryItem[] = theoryItems.sort((a, b) => (a.priority ?? 999) - (b.priority ?? 999));

export function getTheoryCategories() {
  return Array.from(new Set(theories.map((theory) => theory.category)));
}

export function getTheoryByTag(tag: string) {
  const decodedTag = decodeURIComponent(tag);
  return theories.find((theory) => theory.tag === decodedTag || theory.title === decodedTag || theory.subTags?.includes(decodedTag));
}
